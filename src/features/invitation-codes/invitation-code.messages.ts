export type InvitationLocale = "ko" | "ja";

export function resolveInvitationLocale(acceptLanguage: string | null | undefined): InvitationLocale {
  return acceptLanguage?.trim().toLowerCase().startsWith("ja") ? "ja" : "ko";
}

